import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const win=process.platform==='win32';
const compiler=process.env.CC||'gcc';
const name=process.argv[2]??'lock-host';
if(!['lock-host','process-host'].includes(name))throw Error('Unknown native helper');
const source=fileURLToPath(new URL(`./${name}.c`,import.meta.url));
const output=fileURLToPath(new URL(`./${name}${win?'.exe':''}`,import.meta.url));
const r=spawnSync(compiler,[source,'-O2','-Wall',...(win?['-municode']:[]),'-o',output],{stdio:'inherit'});
if(r.error)throw r.error;process.exitCode=r.status;
